#!/usr/bin/env node
/**
 * Write the photo credits the app shows, from the manifest the photo scripts keep.
 *
 * public/pix/manifest.json is the record of where every picture came from, and
 * it is 70 KB of provenance nobody needs at runtime: source URLs, byte counts,
 * fetch dates, and a tile entry for every drawing. The app needs three things
 * per photograph — who took it, the licence, and the Commons file to link to —
 * so this boils it down to exactly that, keyed by recipe id, and writes it into
 * src/data/cookbook-credits.ts. The name is not an accident: vite.config.ts
 * puts anything under src/data/cookbook* in the cookbook chunk, so the credits
 * ride with the recipes instead of weighing on first paint.
 *
 * Why bundled rather than fetched: anything under /pix/ is served cache-first
 * forever by the service worker, so a corrected credit fetched at runtime would
 * never reach anyone who had already opened the app.
 *
 * Author strings are cleaned on the way through. Several were scraped from
 * Commons or Flickr as they stood — a camera location with coordinates, a
 * conversion history, "User:" prefixes, "Name from City, Country" — and none of
 * that is the photographer's name. The clean-up keeps the name and drops only
 * the wiki markup and the location; the six that needed a human are spelled
 * out in AUTHOR_FIX.
 *
 *   npm run credits          after fetch-dish-photos.mjs or make-dish-tiles.mjs
 *
 * pictures.test.ts rebuilds the map in memory and fails if the file is stale.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { RECIPES } from '../src/data/cookbook.js';

const COMMONS = 'https://commons.wikimedia.org/wiki/File:';
export const isPhoto = (pic) => /\.(webp|jpe?g|png)$/i.test(pic);

/** Credits whose scraped author string was beyond a rule. */
const AUTHOR_FIX = {
  banh_mi: 'nsaum75',
  lancashire_hotpot: 'alexcwood',
  rice_and_peas: 'Whispyhistory, Hike395',
  cauliflower_cheese: "Peter O'Connor (AnemoneProjectors)",
  veg_curry: 'Jpatokal (Wikivoyage)',
  kedgeree: 'Justinc',
};

export function cleanAuthor(id, raw) {
  if (AUTHOR_FIX[id]) return AUTHOR_FIX[id];
  return String(raw)
    // Direction marks come along with right-to-left talk-page links.
    .replace(/[\u200e\u200f\u202a-\u202e]/g, '')
    .replace(/^User:\s*/i, '')
    // Flickr's "Name from City, Region, Country" — the place is not the person.
    .replace(/\s+from\s+[^,]+(\s*,\s*[^,]+)*$/, '')
    .replace(/\s+/g, ' ')
    .trim();
}

/** A few photographs were filed under the picture's own name before recipes
 *  had ids, so the recipe id is tried first and the file stem second. */
const stem = (pic) => pic.replace(/^pix\//, '').replace(/\.\w+$/, '');

export function build(manifest, recipes) {
  const out = {};
  for (const r of [...recipes].sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0))) {
    if (!isPhoto(r.pic)) continue;
    const e = manifest[r.id] ?? manifest[stem(r.pic)];
    if (!e?.author || !e?.licence || !e?.page?.startsWith(COMMONS)) {
      throw new Error(`${r.id} (${r.pic}) has no usable credit in the manifest`);
    }
    out[r.id] = [cleanAuthor(r.id, e.author), e.licence, e.page.slice(COMMONS.length)];
  }
  return out;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const manifest = JSON.parse(readFileSync('public/pix/manifest.json', 'utf8'));
  const map = build(manifest, RECIPES);
  const rows = Object.entries(map).map(([id, c]) => `  ${id}: ${JSON.stringify(c)},`);
  writeFileSync(
    'src/data/cookbook-credits.ts',
    `// Generated by scripts/make-photo-credits.mjs from public/pix/manifest.json.
// Do not edit by hand: change the manifest (or the script) and run npm run credits.

/** Photographer, licence, and the Commons file name after "File:". */
export type PhotoCredit = readonly [author: string, licence: string, file: string];

export const PHOTO_CREDITS: Record<string, PhotoCredit> = {
${rows.join('\n')}
};
`,
  );
  console.log(`wrote ${rows.length} photo credits to src/data/cookbook-credits.ts`);
}
